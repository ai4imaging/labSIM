"""The parametric part library.

This is where the design principle lives. Nothing here is generated by a model: each part
is a named mechanism with a fixed topology and a handful of dimensions, and building one is
a deterministic function of those dimensions. A model's only role, in `propose.py`, is to
choose which mechanism and fill in the numbers.

That is what makes the co-design side of the pipeline stable. A model that writes geometry
code fails in unbounded ways — it does not compile, it compiles into something non-manifold,
or it compiles into something that cannot be made. A model that fills in eight floats can
only fail in one way, which pydantic catches before any geometry is built, and which the
manufacturability check in `dfm.py` catches for the rest.

Each part produces three things at once: a watertight mesh for printing and for the visual,
an explicit decomposition into primitives for collision, and named frames for the interfaces
it mates against. The primitive collision model matters — a convex hull of a bracket is not
a bracket, and a mesh collider of one is slow and unstable, whereas four boxes are both fast
and exactly right.
"""

from __future__ import annotations

import math
from abc import ABC, abstractmethod
from typing import Annotated, Literal

import numpy as np
import trimesh
from pydantic import BaseModel, ConfigDict, Field, model_validator

from amx.codesign.materials import DEFAULT_MATERIAL, Material, material
from amx.geometry import Pose, matrix_to_quat

BOOLEAN_ENGINE = "manifold"

FEATHER_EDGE_LIMIT_RAD = math.pi / 4.0
"""Shallowest angle at which a hole may break through a face.

Where a bore meets a face it is not perpendicular to, the material runs out to a point. At
45 deg the resulting edge is still an edge; much below that it is a feather that chips off a
machined part and simply does not print.
"""

BOOLEAN_OVERSHOOT = 5e-5
"""How far volumes are made to overlap before a boolean.

Exact coplanar or tangent surfaces are what makes a mesh boolean produce a non-manifold or
split result, and 50 um is far below anything a machine will resolve.
"""


class Primitive(BaseModel):
    """One convex collision volume, in the part's own frame."""

    model_config = ConfigDict(extra="forbid")

    shape: Literal["box", "cylinder", "sphere", "capsule"]
    size: tuple[float, ...] = Field(
        description="MJCF `size` semantics: box half-extents, cylinder (radius, half-length), "
        "sphere (radius), capsule (radius, half-length)."
    )
    pose: Pose = Field(default_factory=Pose)
    role: str = Field(
        default="",
        description="What this volume is, in the template's own terms — `floor`, `wall`, "
        "`jaw`. Becomes the geom's name, which is how a plan can say 'the part must touch "
        "the well floor' and how the judge can measure insertion depth. Without it the "
        "collision set is an unlabelled pile of boxes and no rule can refer to any of it.",
    )

    def volume(self) -> float:
        match self.shape:
            case "box":
                return 8.0 * self.size[0] * self.size[1] * self.size[2]
            case "cylinder":
                return math.pi * self.size[0] ** 2 * 2.0 * self.size[1]
            case "sphere":
                return 4.0 / 3.0 * math.pi * self.size[0] ** 3
            case "capsule":
                return math.pi * self.size[0] ** 2 * 2.0 * self.size[1] + (
                    4.0 / 3.0 * math.pi * self.size[0] ** 3
                )
        raise ValueError(self.shape)

    def minimum_extent(self) -> float:
        match self.shape:
            case "box":
                return 2.0 * min(self.size[:3])
            case "cylinder" | "capsule":
                return 2.0 * self.size[0]
            case "sphere":
                return 2.0 * self.size[0]
        raise ValueError(self.shape)


class PartGeometry(BaseModel):
    """Everything downstream needs from a built part."""

    model_config = ConfigDict(extra="forbid", arbitrary_types_allowed=True)

    part_id: str
    template: str
    mesh: trimesh.Trimesh
    collision: list[Primitive]
    frames: dict[str, Pose] = Field(
        default_factory=dict,
        description="Named interfaces, exported as MJCF sites so the plan can target them.",
    )
    material: Material
    parameters: dict[str, float] = Field(default_factory=dict)
    stated_clearances: dict[str, float] = Field(
        default_factory=dict,
        description="Fits the part claims to provide, checked against the material's allowance.",
    )

    @property
    def mass_kg(self) -> float:
        return self.material.mass_of(float(self.mesh.volume))

    @property
    def extents_m(self) -> tuple[float, float, float]:
        return tuple(float(v) for v in self.mesh.extents)  # type: ignore[return-value]


class Part(BaseModel, ABC):
    """Base for every template. Subclasses declare parameters and implement `build`."""

    model_config = ConfigDict(extra="forbid")

    part_id: str = Field(pattern=r"^[a-z0-9][a-z0-9_]*$")
    material_key: str = Field(default=DEFAULT_MATERIAL.key)

    @property
    def material(self) -> Material:
        return material(self.material_key)

    @abstractmethod
    def build(self) -> PartGeometry: ...

    def _finish(
        self,
        mesh: trimesh.Trimesh,
        collision: list[Primitive],
        frames: dict[str, Pose],
        *,
        clearances: dict[str, float] | None = None,
    ) -> PartGeometry:
        # Merge coincident vertices, but do not let trimesh "validate": that drops degenerate
        # faces, and a sliver triangle left by a boolean is often the only thing closing a
        # corner. Removing it turns a watertight solid into one with a hole. A 20 um sliver
        # bothers neither a slicer nor MuJoCo; an open mesh bothers both.
        mesh.process(validate=False)
        return PartGeometry(
            part_id=self.part_id,
            template=self.template,  # type: ignore[attr-defined]
            mesh=mesh,
            collision=collision,
            frames=frames,
            material=self.material,
            parameters={
                k: float(v)
                for k, v in self.model_dump().items()
                if isinstance(v, (int, float)) and not isinstance(v, bool)
            },
            stated_clearances=clearances or {},
        )


