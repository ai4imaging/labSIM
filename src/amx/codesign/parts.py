def _frame_walls(
    outer_x: float, outer_y: float, outer_z: float, wall: float, floor: float
) -> list[Primitive]:
    """Four walls and a floor: the collision model of any open-topped box."""
    wall_height = outer_z - floor
    mid_z = floor + wall_height / 2.0
    return [
        # `floor` is named because a plan can require the part it places to be resting on
        # it, which is the difference between seated and perched on the rim.
        Primitive(
            role="floor",
            shape="box",
            size=(outer_x / 2.0, outer_y / 2.0, floor / 2.0),
            pose=Pose(pos=(0.0, 0.0, floor / 2.0)),
        ),
        Primitive(
            role="wall_x_low",
            shape="box",
            size=(wall / 2.0, outer_y / 2.0, wall_height / 2.0),
            pose=Pose(pos=(-(outer_x - wall) / 2.0, 0.0, mid_z)),
        ),
        Primitive(
            role="wall_x_high",
            shape="box",
            size=(wall / 2.0, outer_y / 2.0, wall_height / 2.0),
            pose=Pose(pos=((outer_x - wall) / 2.0, 0.0, mid_z)),
        ),
        Primitive(
            role="wall_y_low",
            shape="box",
            size=((outer_x - 2.0 * wall) / 2.0, wall / 2.0, wall_height / 2.0),
            pose=Pose(pos=(0.0, -(outer_y - wall) / 2.0, mid_z)),
        ),
        Primitive(
            role="wall_y_high",
            shape="box",
            size=((outer_x - 2.0 * wall) / 2.0, wall / 2.0, wall_height / 2.0),
            pose=Pose(pos=(0.0, (outer_y - wall) / 2.0, mid_z)),
        ),
    ]


def _well_dividers(
    rows: int, columns: int, pitch: float, well_radius: float, height: float, wall: float
) -> list[Primitive]:
    """The material between adjacent wells, as thin slabs.

    Without these a tube dropped into an interior well would fall straight through to a
    neighbour, because the outer frame alone does not separate them.
    """
    divider = pitch - 2.0 * well_radius
    if divider <= 1e-5:
        return []
    wall_height = height - wall
    mid_z = wall + wall_height / 2.0
    out: list[Primitive] = []
    for column in range(columns - 1):
        x = (column - (columns - 1) / 2.0 + 0.5) * pitch
        out.append(
            Primitive(
                role=f"divider_x{column}",
                shape="box",
                size=(divider / 2.0, (rows * pitch) / 2.0, wall_height / 2.0),
                pose=Pose(pos=(x, 0.0, mid_z)),
            )
        )
    for row in range(rows - 1):
        y = (row - (rows - 1) / 2.0 + 0.5) * pitch
        out.append(
            Primitive(
                role=f"divider_y{row}",
                shape="box",
                size=((columns * pitch) / 2.0, divider / 2.0, wall_height / 2.0),
                pose=Pose(pos=(0.0, y, mid_z)),
            )
        )
    return out


def _translate(offset: tuple[float, float, float]) -> np.ndarray:
    matrix = np.eye(4)
    matrix[:3, 3] = offset
    return matrix


def pose_from_matrix(matrix: np.ndarray) -> Pose:
    """Convert a homogeneous transform to a `Pose`, via the quaternion."""
    quat = matrix_to_quat(matrix[:3, :3])
    # MJCF takes a quaternion directly, but `Pose` carries Euler angles, so go through them.
    w, x, y, z = quat
    roll = math.atan2(2.0 * (w * x + y * z), 1.0 - 2.0 * (x * x + y * y))
    sin_pitch = max(-1.0, min(1.0, 2.0 * (w * y - z * x)))
    pitch = math.asin(sin_pitch)
    yaw = math.atan2(2.0 * (w * z + x * y), 1.0 - 2.0 * (y * y + z * z))
    return Pose(pos=tuple(float(v) for v in matrix[:3, 3]), euler=(roll, pitch, yaw))
