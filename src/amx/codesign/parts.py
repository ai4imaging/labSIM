def template_schema(name: str) -> dict[str, object]:
    """The JSON schema for one template's parameters, for a model to fill in."""
    try:
        return TEMPLATES[name].model_json_schema()
    except KeyError:
        raise KeyError(
            f"unknown template {name!r}; available: {', '.join(sorted(TEMPLATES))}"
        ) from None


